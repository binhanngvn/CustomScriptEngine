namespace CustomScriptEngine.Core;

/// <summary>
/// Plain-text cache of absolute DLL paths discovered from the target game's
/// Managed folder, BepInEx folders and scripts/libs. The cache is consumed by
/// the compiler; discovery is deliberately done by the Unity host at startup.
/// </summary>
public static class ReferenceCache
{
    private const string Header = "# Custom Script Engine reference cache v2";

    public static IReadOnlyList<string> Load(string cachePath)
    {
        if (!File.Exists(cachePath))
            return Array.Empty<string>();

        try
        {
            var result = new List<string>();
            foreach (var line in File.ReadAllLines(cachePath))
            {
                var value = line.Trim();
                if (string.IsNullOrWhiteSpace(value) || value.StartsWith("#", StringComparison.Ordinal))
                    continue;

                try
                {
                    if (value.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                        result.Add(Path.GetFullPath(value));
                }
                catch
                {
                    // Ignore malformed paths. The host can rebuild the cache.
                }
            }

            return result
                .Where(File.Exists)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .OrderBy(x => x, StringComparer.OrdinalIgnoreCase)
                .ToList();
        }
        catch
        {
            return Array.Empty<string>();
        }
    }

    public static void Save(string cachePath, IEnumerable<string> dllPaths)
    {
        var fullPath = Path.GetFullPath(cachePath);
        var directory = Path.GetDirectoryName(fullPath);
        if (!string.IsNullOrWhiteSpace(directory))
            Directory.CreateDirectory(directory);

        var lines = new List<string>
        {
            Header,
            "# Generated by Custom Script Engine. Do not edit unless you know what you are doing."
        };

        lines.AddRange(
            dllPaths
                .Where(File.Exists)
                .Select(Path.GetFullPath)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .OrderBy(x => x, StringComparer.OrdinalIgnoreCase));

        File.WriteAllLines(fullPath, lines);
    }
}
